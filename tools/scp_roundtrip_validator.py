"""
SCP Round-Trip Validator

Checks that ED9-VM .dat scripts follow the layout rules ScpWriter relies on for a byte-exact
round trip, and optionally decompiles, recompiles and byte-compares each file.

The checks live in tools/round_trip/, a module per job; this script is the command line.

Usage:
    python tools/scp_roundtrip_validator.py falcom/ed9/games/sora2/extracted/script_en/scena/e2000.dat
    python tools/scp_roundtrip_validator.py falcom/ed9/games/sora2/extracted/script_en --verbose
    python tools/scp_roundtrip_validator.py falcom/ed9/games/sora2/extracted/script_en/scena/e0000.dat --round-trip --game sora2
    python tools/scp_roundtrip_validator.py falcom/ed9/games/sora2/extracted/script_en/scena/e0000.dat --logic-round-trip --game sora2

--game <game>: the game whose common-function library and writer the decompiles of --round-trip and --logic-round-trip
use (falcom/ed9/games/<game>/); without it none: every common function inline, no library import in the .py, and the
shared ScpWriter, which writes as the sora games do.

Checks (FAIL = a rule the writer depends on is broken, WARN = known decompiler limitation):
    layout          default params, param flags, debug records and debug args are contiguous in table
                    order; every per-function offset is the running position (even for count 0);
                    global_var_offset ends the debug args, and the global var table (8 bytes/entry:
                    name ref, type) ends where the code starts
    function order  table sorted by name bytes; code in source order: common functions first (no line
                    numbers), then strictly increasing DEBUG_SET_LINENO
    code            PUSH size byte; PUSH_CURRENT_FUNC_ID value == caller table index;
                    WARN: unreachable code (kept in the byte-exact <stem>.llil.py; the everyday decompile
                    drops it and logs it)
    string pool     never deduplicated: code refs (code order, unreachable code included), names, default
                    strings, debug-only strings, global var names (index order, always last);
                    falcom/ed9/structs/string_pool.py
    debug records   every record rebuilt from its call site, dead code included (call_debug_records.pair_records);
                    WARN: a call the compiler left without a record (aligned)
    round trip      (--round-trip) decompile into a work dir, delete the copy, run the generated byte-exact
                    <stem>.llil.py (byte_exact_decompile, process_file's with write_llil_py and round_trip),
                    byte-compare with the original; when they differ, also compare the two files' debug
                    records function by function (the first difference in each, see compare_file_records)

--logic-round-trip checks (decompile with round_trip=False, the everyday config; see docs/ROUND_TRIP_POLICY.md
for the full policy - byte-exact fidelity is not required, preserved game logic and a byte-level
fixed point within a few rounds are). With --game each decompile is the mixed <stem>.py (logic_decompile, the steps
scp2py_base.py's process_file takes): each function whose HLIL DSL text lowers exactly to its code written in the HLIL
DSL, the rest in the LLIL DSL (docs/dsl/HLIL_DSL.md); without it the all-LLIL .py, since a mixed file needs its game's
DSL helper:
    source preconditions   fields the decompile normalizes away that no check on a recompiled file
                            could see (duplicate names, header dword_14, name_hash, instruction-range
                            validity, call pairing)
    reachability            every dropped byte range is provably dead (see is_range_provably_dead)
    string fidelity         every pooled string re-encodes to exactly its raw bytes
    round N logic preserved  source vs that round's decompile: per-function fingerprint + signature,
                            the global table, and header dword_14 - checked every round, not just once; a
                            function the source decompile printed in the HLIL DSL, which writes no line
                            markers, is fingerprinted without its DEBUG_SET_LINENO
    round N mode            that round's decompile prints exactly the source decompile's HLIL functions in
                            the HLIL DSL
    round N records kept    source vs that round's call-site records, call by call: the right callee, its
                            constants and its place; excused by reason (docs/ROUND_TRIP_POLICY.md, Records
                            the engine reads) and counted in the summary
    logic round trip        PASS once compiled bytes and decompiled text both stop changing, within
                            MAX_CONVERGENCE_ROUNDS rounds; FAIL otherwise
Name inputs <name>.dat: the generated header names its output after the whole file name, so a
two-suffix input (X.original.dat) compiles to X.original.dat and the round is reported as a failed
compile.

Baseline (2026-10-01, sora2's scripts under script_en/, format checks, no FAIL; all five byte-identical under
--round-trip and converged at round 2 under --logic-round-trip):
    scena/e0000.dat           PASS, 1 debug record
    scena/e2000.dat           PASS, 235 debug records (42 with dropped default args)
    scena/system.dat          WARN: 63 unreachable ranges, 4806 debug records (740 dropped)
    scena/mp0000_ev.dat       WARN: 3 unreachable JMPs, 19461 debug records (7872 dropped)
    ai/ai_chr0100_e00.dat     WARN: 1 unreachable JMP, 37 debug records
"""

import argparse
import sys
import tempfile
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from dc3.utils import collect_paths
from falcom.ed9.games import game_names
from round_trip.byte_round_trip import check_round_trip
from round_trip.format_checks import check_common_order, validate_file
from round_trip.logic_round_trip import check_logic_round_trip
from round_trip.results import MAX_DETAILS, CheckResult, Status, exception_text


DETAIL_INDENT = ' ' * 10


def print_result(result: CheckResult, verbose: bool):
    print(f'  {result.status.name:<4}  {result.name:<14}  {result.summary}')

    if result.status == Status.PASS and not verbose:
        return

    details = result.details if verbose else result.details[:MAX_DETAILS]
    for line in details:
        print(f'{DETAIL_INDENT}{line}')

    if len(details) < len(result.details):
        print(f'{DETAIL_INDENT}... {len(result.details) - len(details)} more (--verbose)')


def create_parser() -> argparse.ArgumentParser:
    arg_parser = argparse.ArgumentParser(
        description='Validate ED9-VM .dat scripts against the byte-exact round-trip rules')
    arg_parser.add_argument('paths', nargs='+', help='.dat files or directories (searched recursively)')
    arg_parser.add_argument('--round-trip', action='store_true', help='decompile, recompile and byte-compare each file')
    arg_parser.add_argument('--logic-round-trip', action='store_true', help='decompile with round_trip=False and verify game logic is preserved and compile/decompile reaches a fixed point')
    arg_parser.add_argument('--work-dir', metavar='DIR', help='where --round-trip / --logic-round-trip write their files (default: a new temp dir)')
    arg_parser.add_argument('--game', choices=game_names(),
                            help="the game whose common-function library and writer --round-trip / --logic-round-trip's decompiles use (default: none, every common function inline, the shared ScpWriter)")
    arg_parser.add_argument('--verbose', action='store_true', help='print every detail, including for passing checks')
    return arg_parser


def main() -> int:
    args = create_parser().parse_args()
    files = collect_paths(args.paths)

    work_dir = None
    if args.round_trip or args.logic_round_trip:
        work_dir = Path(args.work_dir) if args.work_dir else Path(tempfile.mkdtemp(prefix='scp_roundtrip_'))
        work_dir.mkdir(parents=True, exist_ok=True)
        print(f'work dir: {work_dir}')
        print(f'game: {args.game or 'none'}')

    totals = Counter()
    common_orders = {}

    for path in files:
        print(f'== {path}')

        try:
            results, common_orders[path] = validate_file(path)
        except Exception as e:
            results = [CheckResult('load', Status.FAIL, exception_text(e))]

        if args.round_trip:
            try:
                results.append(check_round_trip(path, work_dir, game=args.game))
            except Exception as e:
                results.append(CheckResult('round trip', Status.FAIL, exception_text(e)))

        if args.logic_round_trip:
            try:
                results.extend(check_logic_round_trip(path, work_dir, game=args.game))
            except Exception as e:
                results.append(CheckResult('logic round trip', Status.FAIL, exception_text(e)))

        for result in results:
            print_result(result, args.verbose)

        totals[max(result.status for result in results)] += 1

    if len(common_orders) > 1:
        print('== all files')
        print_result(check_common_order(common_orders), args.verbose)

    print(f'== {len(files)} files: ' + ', '.join(f'{totals[status]} {status.name}' for status in Status))
    return 1 if totals[Status.FAIL] else 0


if __name__ == '__main__':
    sys.exit(main())
